export function numberedProblemNumber(id: string): number | undefined {
  if (Object.hasOwn(numbers, id)) return numbers[id]
  const sourceId = /^dailycoding-([1-9]\d*)$/.exec(id)?.[1]
  const number = Number(sourceId) + 10_000
  return Number.isSafeInteger(number) ? number : undefined
}

export function numberedProblemPath(number: number, lang?: string): string {
  const path = `/study/algorithms/${number}`
  return lang ? `${path}?lang=${encodeURIComponent(lang)}` : path
}

export function exercisePath(studyId: string, id: string): string {
  const number = numberedProblemNumber(id)
  return number === undefined ? `/study/${studyId}/practice/${id}` : numberedProblemPath(number, studyId)
}
