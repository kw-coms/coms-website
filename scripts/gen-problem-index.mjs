#!/usr/bin/env node
// Writes src/pages/study/exercises/problemIndex.ts: id, title and study of every problem, without the
// statements, so the /study hub can show counts without loading the 200 kB problem bodies.
// Run after adding or renaming a problem: node --import tsx scripts/gen-problem-index.mjs
// tests/studyProblemIndex.test.mjs fails while the file is stale.

import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { exercisesFor } from '../src/pages/study/exercises/problems/index.ts'
import { STUDIES } from '../src/pages/study/studies.ts'

export const INDEX_PATH = resolve(dirname(fileURLToPath(import.meta.url)), '../src/pages/study/exercises/problemIndex.ts')

export function renderIndex() {
  const rows = STUDIES.flatMap((study) => exercisesFor(study.id).map((p) => ({ id: p.id, title: p.title, study: study.id })))
  const lines = rows.map((row) => `  ${JSON.stringify(row)},`)
  return `// Generated by scripts/gen-problem-index.mjs: do not edit. One row per problem per study (a shared problem appears once for each study it is offered in).
export interface ProblemMeta { id: string; title: string; study: string }

export const problemIndex: ProblemMeta[] = [
${lines.join('\n')}
]
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(INDEX_PATH, renderIndex())
