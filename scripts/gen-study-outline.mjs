#!/usr/bin/env node
// Writes src/pages/study/studyOutline.ts: the top-level chapters (anchor id and title) of each study, read from the
// table of contents in content/<id>.html. Quick search uses it, so Ctrl+K finds a chapter without loading the lessons.
// Run after editing a table of contents: node --import tsx scripts/gen-study-outline.mjs
// tests/studyOutline.test.mjs fails while the file is stale.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { STUDIES } from '../src/pages/study/studies.ts'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../src/pages/study')
export const OUTLINE_PATH = resolve(root, 'studyOutline.ts')

// `&amp;` goes last: decoding it first would turn `&amp;lt;` into `&lt;` and then into `<`.
const decode = (text) => text.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, '&')

export function renderOutline() {
  const outline = {}
  for (const study of STUDIES) {
    const html = readFileSync(resolve(root, `content/${study.id}.html`), 'utf8')
    const toc = html.match(/<nav class="toc"[\s\S]*?<\/nav>/)?.[0] ?? ''
    // `<li>` with no class is a chapter; `<li class="sub">` is a section inside one.
    outline[study.id] = [...toc.matchAll(/<li><a href="#([^"]+)">([^<]+)<\/a><\/li>/g)].map((m) => ({ id: m[1], title: decode(m[2]).trim() }))
    if (outline[study.id].length === 0) throw new Error(`no chapters found in content/${study.id}.html`)
  }
  return `// Generated by scripts/gen-study-outline.mjs: do not edit. Top-level chapters of each study (anchor id, title).
export const studyOutline: Record<string, { id: string; title: string }[]> = ${JSON.stringify(outline, null, 2)}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(OUTLINE_PATH, renderOutline())
