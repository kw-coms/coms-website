ALTER TABLE club_projects ADD COLUMN owner_student_id VARCHAR(30);
CREATE INDEX idx_club_projects_owner ON club_projects(owner_student_id);

CREATE TABLE club_project_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_project_id BIGINT NOT NULL REFERENCES club_projects(id),
    stored_name VARCHAR(255) NOT NULL,
    mime_type VARCHAR(20) NOT NULL,
    position INTEGER NOT NULL
);
CREATE INDEX idx_club_project_images_project ON club_project_images(club_project_id, position, id);
