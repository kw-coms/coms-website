ALTER TABLE club_projects ADD COLUMN view_count BIGINT NOT NULL DEFAULT 0;

CREATE TABLE club_project_likes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_project_id BIGINT NOT NULL REFERENCES club_projects(id) ON DELETE CASCADE,
    student_id VARCHAR(30) NOT NULL REFERENCES members(student_id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_club_project_likes_member UNIQUE (club_project_id, student_id)
);
CREATE INDEX idx_club_project_likes_student ON club_project_likes(student_id);

CREATE TABLE club_project_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_project_id BIGINT NOT NULL REFERENCES club_projects(id) ON DELETE CASCADE,
    student_id VARCHAR(30) NOT NULL REFERENCES members(student_id) ON DELETE CASCADE,
    author_name VARCHAR(100) NOT NULL,
    content TEXT NOT NULL,
    parent_comment_id BIGINT REFERENCES club_project_comments(id) ON DELETE CASCADE,
    depth INTEGER NOT NULL DEFAULT 0 CHECK (depth BETWEEN 0 AND 30),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_club_project_comments_work ON club_project_comments(club_project_id, created_at, id);
CREATE INDEX idx_club_project_comments_author ON club_project_comments(student_id);
CREATE INDEX idx_club_project_comments_parent ON club_project_comments(parent_comment_id);
