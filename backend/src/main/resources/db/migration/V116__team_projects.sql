-- 팀 프로젝트(팀프): 프로그램 > 일정(마일스톤) / 팀 > 팀원 / 제출(본문·링크·파일).
CREATE TABLE team_projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL,
    description VARCHAR(5000) NOT NULL DEFAULT '',
    open BOOLEAN NOT NULL DEFAULT TRUE,
    created_by VARCHAR(50),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE team_project_milestones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id BIGINT NOT NULL REFERENCES team_projects (id) ON DELETE CASCADE,
    title VARCHAR(120) NOT NULL,
    description VARCHAR(2000) NOT NULL DEFAULT '',
    starts_at TIMESTAMP,
    due_at TIMESTAMP,
    -- 종일: 날짜만 의미가 있다. 시작은 그날 00:00, 마감은 그날 23:59:59(Asia/Seoul)까지로 본다.
    all_day BOOLEAN NOT NULL DEFAULT FALSE,
    submittable BOOLEAN NOT NULL DEFAULT FALSE,
    position INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_team_project_milestones_program ON team_project_milestones (program_id, position);

CREATE TABLE team_project_teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id BIGINT NOT NULL REFERENCES team_projects (id) ON DELETE CASCADE,
    name VARCHAR(60) NOT NULL,
    topic VARCHAR(200) NOT NULL DEFAULT '',
    intro VARCHAR(2000) NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_team_project_team_name UNIQUE (program_id, name)
);

-- 한 회원은 한 프로그램에서 한 팀에만 속한다(program_id 를 함께 둔 이유).
CREATE TABLE team_project_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id BIGINT NOT NULL REFERENCES team_projects (id) ON DELETE CASCADE,
    team_id BIGINT NOT NULL REFERENCES team_project_teams (id) ON DELETE CASCADE,
    student_id VARCHAR(255) NOT NULL REFERENCES members (student_id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_team_project_member_once UNIQUE (program_id, student_id)
);
CREATE INDEX idx_team_project_members_team ON team_project_members (team_id);
CREATE INDEX idx_team_project_members_student ON team_project_members (student_id);

CREATE TABLE team_project_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id BIGINT NOT NULL REFERENCES team_projects (id) ON DELETE CASCADE,
    team_id BIGINT NOT NULL REFERENCES team_project_teams (id) ON DELETE CASCADE,
    milestone_id BIGINT NOT NULL REFERENCES team_project_milestones (id) ON DELETE CASCADE,
    body VARCHAR(20000) NOT NULL DEFAULT '',
    submitted_by VARCHAR(255) NOT NULL,
    submitted_by_name VARCHAR(255) NOT NULL,
    updated_by VARCHAR(255) NOT NULL,
    updated_by_name VARCHAR(255) NOT NULL,
    submitted_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_team_project_submission UNIQUE (team_id, milestone_id)
);
CREATE INDEX idx_team_project_submissions_program ON team_project_submissions (program_id);
CREATE INDEX idx_team_project_submissions_milestone ON team_project_submissions (milestone_id);

CREATE TABLE team_project_submission_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL REFERENCES team_project_submissions (id) ON DELETE CASCADE,
    url VARCHAR(2000) NOT NULL,
    position INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_team_project_links_submission ON team_project_submission_links (submission_id);

CREATE TABLE team_project_submission_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL REFERENCES team_project_submissions (id) ON DELETE CASCADE,
    original_name VARCHAR(255) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    file_size BIGINT NOT NULL,
    stored_name VARCHAR(255) NOT NULL,
    uploaded_by VARCHAR(255) NOT NULL,
    uploaded_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_team_project_files_submission ON team_project_submission_files (submission_id);
