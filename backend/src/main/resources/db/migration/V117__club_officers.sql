-- 역대 회장단: 임기(대) > 임원(회장/부회장). 임원은 명부(eligible_members) 행과 선택적으로 연결해 기수를 보여 준다.
CREATE TABLE club_officer_terms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label VARCHAR(20) NOT NULL,
    -- year 는 H2 예약어라 따옴표로 감싼다(PostgreSQL 에서는 같은 컬럼).
    "year" INTEGER NOT NULL,
    -- 같은 해 안의 순서(학기). 클수록 나중 임기.
    position INTEGER NOT NULL DEFAULT 0,
    note VARCHAR(200) NOT NULL DEFAULT '',
    CONSTRAINT uq_club_officer_terms_label UNIQUE (label)
);

CREATE TABLE club_officers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_id BIGINT NOT NULL REFERENCES club_officer_terms (id) ON DELETE CASCADE,
    role VARCHAR(20) NOT NULL CHECK (role IN ('PRESIDENT', 'VICE_PRESIDENT')),
    name VARCHAR(40) NOT NULL,
    eligible_member_id BIGINT NULL REFERENCES eligible_members (id) ON DELETE SET NULL,
    position INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_club_officers_term ON club_officers (term_id);
CREATE INDEX idx_club_officers_eligible_member ON club_officers (eligible_member_id);
