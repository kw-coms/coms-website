CREATE TABLE IF NOT EXISTS external_opportunities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key VARCHAR(50) NOT NULL,
    external_id VARCHAR(200) NOT NULL,
    source_fingerprint CHAR(64) NOT NULL,
    draft_json TEXT NOT NULL,
    published_json TEXT,
    published_at TIMESTAMP WITH TIME ZONE,
    collected_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(10) NOT NULL CHECK (status IN ('PENDING', 'PUBLISHED', 'IGNORED')),
    ai_assisted BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0,
    UNIQUE (source_key, external_id)
);

CREATE INDEX IF NOT EXISTS idx_external_opportunity_queue ON external_opportunities(status, collected_at, id);
CREATE INDEX IF NOT EXISTS idx_external_opportunity_publication ON external_opportunities(published_at);

CREATE TABLE IF NOT EXISTS external_opportunity_collection (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    lease_token VARCHAR(36),
    lease_until TIMESTAMP WITH TIME ZONE,
    next_at TIMESTAMP WITH TIME ZONE,
    last_run_at TIMESTAMP WITH TIME ZONE,
    source_report_json TEXT,
    ai_usage_day DATE,
    ai_attempts INTEGER NOT NULL DEFAULT 0 CHECK (ai_attempts >= 0)
);

INSERT INTO external_opportunity_collection (id)
SELECT 1 WHERE NOT EXISTS (SELECT 1 FROM external_opportunity_collection WHERE id = 1);
