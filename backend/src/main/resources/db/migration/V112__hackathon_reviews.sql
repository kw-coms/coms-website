CREATE TABLE hackathon_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id VARCHAR(40) NOT NULL CHECK (project_id IN ('wargether', 'underground-route', 'still')),
    generation INTEGER NOT NULL CHECK (generation BETWEEN 0 AND 60),
    name VARCHAR(40) NOT NULL,
    name_key VARCHAR(80) NOT NULL,
    chair BOOLEAN NOT NULL DEFAULT FALSE,
    theme_fit INTEGER NOT NULL CHECK (theme_fit BETWEEN 0 AND 20),
    creativity INTEGER NOT NULL CHECK (creativity BETWEEN 0 AND 20),
    technology INTEGER NOT NULL CHECK (technology BETWEEN 0 AND 20),
    completeness INTEGER NOT NULL CHECK (completeness BETWEEN 0 AND 20),
    practicality INTEGER NOT NULL CHECK (practicality BETWEEN 0 AND 20),
    feedback VARCHAR(2000) NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_hackathon_review_identity UNIQUE (project_id, generation, name_key),
    CONSTRAINT ck_hackathon_chair_generation CHECK (chair = (generation = 0))
);
