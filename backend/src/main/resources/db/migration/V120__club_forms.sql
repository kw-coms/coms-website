CREATE TABLE IF NOT EXISTS club_forms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL,
    description VARCHAR(3000) NOT NULL,
    category VARCHAR(24) NOT NULL,
    hackathon_event_id BIGINT REFERENCES hackathon_events(id),
    questions_json TEXT NOT NULL,
    accepting BOOLEAN NOT NULL,
    closes_at TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS club_form_responses (
    form_id BIGINT NOT NULL REFERENCES club_forms(id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    answers_json TEXT NOT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (form_id, member_id)
);

CREATE INDEX IF NOT EXISTS idx_club_form_responses_member ON club_form_responses(member_id);
